#!/usr/bin/env sh
# Generate deploy/.env with fresh secrets and required public/AI settings.
# Run from the repository or from an extracted orbit-deploy release bundle:
#   sh init-env.sh
# Non-interactive use (for automation): pre-set ORBIT_PUBLIC_ORIGIN,
# ORBIT_AI_BASE_URL, ORBIT_AI_API_KEY and ORBIT_AI_MODEL in the environment.
set -eu
umask 077

DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
cd "$DIR"

if [ -f .env ]; then
  echo "deploy/.env already exists; refusing to overwrite." >&2
  echo "Remove or rename it first if you intentionally want to regenerate." >&2
  exit 1
fi

random_hex() {
  od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'
}

prompt_value() {
  prompt="$1"
  default="${2:-}"
  current="${3:-}"
  if [ -n "$current" ]; then
    printf '%s\n' "$current"
    return 0
  fi
  if [ -n "$default" ]; then
    printf '%s [%s]: ' "$prompt" "$default" >&2
  else
    printf '%s: ' "$prompt" >&2
  fi
  IFS= read -r answer || answer=""
  if [ -n "$answer" ]; then
    printf '%s\n' "$answer"
  else
    printf '%s\n' "$default"
  fi
}

require_no_newline_or_quote() {
  name="$1"
  value="$2"
  case "$value" in
    *"'"*|*"
"*)
      echo "$name contains a single quote or newline; use a value without those characters." >&2
      exit 1
      ;;
  esac
}

write_env() {
  name="$1"
  value="$2"
  require_no_newline_or_quote "$name" "$value"
  printf "%s='%s'\n" "$name" "$value" >> .env
}

public_origin="$(prompt_value 'Public HTTPS origin (for example https://orbit.example.com)' '' "${ORBIT_PUBLIC_ORIGIN:-}")"
ai_base_url="$(prompt_value 'OpenAI-compatible AI base URL ending in /v1' '' "${ORBIT_AI_BASE_URL:-}")"
ai_api_key="$(prompt_value 'AI API key' '' "${ORBIT_AI_API_KEY:-}")"
ai_model="$(prompt_value 'AI model name' '' "${ORBIT_AI_MODEL:-}")"

if [ -z "$public_origin" ] || [ -z "$ai_base_url" ] || [ -z "$ai_api_key" ] || [ -z "$ai_model" ]; then
  echo "ORBIT_PUBLIC_ORIGIN, ORBIT_AI_BASE_URL, ORBIT_AI_API_KEY and ORBIT_AI_MODEL are required." >&2
  exit 1
fi

case "$public_origin" in
  https://*) ;;
  *) echo "ORBIT_PUBLIC_ORIGIN must start with https:// for production." >&2; exit 1 ;;
esac

db_password="$(random_hex 24)"
token_secret="$(random_hex 32)"
admin_token="$(random_hex 24)"

printf '# Generated by deploy/init-env.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > .env
write_env ORBIT_DB_PASSWORD "$db_password"
write_env VERRUCKT_ACCESS_TOKEN_SECRET "$token_secret"
write_env ORBIT_ADMIN_TOKEN "$admin_token"
write_env ORBIT_PUBLIC_ORIGIN "$public_origin"
write_env ORBIT_HTTP_BIND "${ORBIT_HTTP_BIND:-127.0.0.1}"
write_env ORBIT_HTTP_PORT "${ORBIT_HTTP_PORT:-1420}"
write_env ORBIT_AI_BASE_URL "$ai_base_url"
write_env ORBIT_AI_API_KEY "$ai_api_key"
write_env ORBIT_AI_MODEL "$ai_model"
write_env ORBIT_AI_PROTOCOL "${ORBIT_AI_PROTOCOL:-chat_completions}"
write_env ORBIT_EMBEDDING_MODEL "${ORBIT_EMBEDDING_MODEL:-}"
write_env ORBIT_BRAVE_API_KEY "${ORBIT_BRAVE_API_KEY:-}"
write_env VERRUCKT_ENV production
chmod 600 .env

echo "Created $DIR/.env with freshly generated secrets." >&2
echo "Review it, then run:" >&2
echo "  sh preflight.sh" >&2
echo "  sh deploy.sh" >&2
